# Fixed-point lookup tables (the target has no FPU and no float runtime): after TONITOR's, itself after
# Felucca's tools/gen_tables.py (Leo Kuroshita, GPL-3.0): SINE, the pitch table. The single-cycle waves of the
# Digitone II-style machines (osc.c), band-limited by octave.
"""tools/gen_tables.py OUT.h"""
import math
import sys
from pathlib import Path

FS = 44100
CTL = 32


def arr(name, ctype, vals, per=12, ram=False):
    # ram: not const, so in .data, copied to RAM at start-up (a table read every sample: the flash is ~3x slower)
    out = ([f"static {ctype} {name}[{len(vals)}] RAMTAB = {{"] if ram else      # (RAMTAB: fw.c's .data placement;
           [f"static const {ctype} {name}[{len(vals)}] = {{"])                 #  the compiler would fold it to flash)
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main(path):
    L = ["/* generated by tools/gen_tables.py */", "#pragma once", "#include <stdint.h>",
         f"#define FS {FS}", f"#define CTL {CTL}", ""]
    # (1025 points: SINE[i + 1] needs no wrap)
    L += arr("SINE", "int16_t", [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)])
    # phase increment (2^32 = one cycle a sample) of pitch p in 1/16 semitone, MIDI 0..127: the top octave
    inc = []
    for p in range(128 * 16):
        f = 440.0 * 2 ** ((p / 16 - 69) / 12)
        inc.append(min(int(f / FS * 2 ** 32), 0x7FFFFFFF))
    L += arr("PITCH_OCT", "uint32_t", inc[2048 - 192:], 8)
    L += ["/* phase increment of pitch p, 1/16 semitone 0..2047: the top octave's entry, k octaves down */",
          "static inline uint32_t pitch_inc(int32_t p)",
          "{",
          "    uint32_t k;",
          "    if (p < 0)",
          "        p = 0;",
          "    if (p > 2047)",
          "        p = 2047;",
          "    k = (2047u - (uint32_t)p) / 192u;",
          "    return PITCH_OCT[(uint32_t)p + 192u * k - (2048u - 192u)] >> k;",
          "}"]
    # 2^(i / 256), Q16, i = 0..256: the fractional part of exp2 (dsp.h exp2_q16)
    L += arr("EXP2_FRAC", "uint32_t", [int(round(65536 * 2 ** (i / 256))) for i in range(257)], 8)
    # log2(1 + i / 256), Q16, i = 0..256 (dsp.h log2_q16)
    L += arr("LOG2_FRAC", "uint32_t", [int(round(65536 * math.log2(1 + i / 256))) for i in range(257)], 8)
    # tanh(x) for x = 0 .. 4 in 512 steps, Q15 (dsp.h tanh_q15)
    L += arr("TANH_Q15", "int16_t", [int(round(32767 * math.tanh(4 * i / 512))) for i in range(513)], ram=True)
    # the state-variable filter's g = tan(pi f / FS), f linear 0 .. 0.45 FS in 512 steps, Q24
    fmax = 0.45 * FS
    L += [f"#define TANG_FMAX {int(fmax)}"]
    L += arr("TAN_G", "uint32_t", [int(round((1 << 24) * math.tan(math.pi * (fmax * i / 512) / FS))) for i in range(513)], 8)
    # the delay's lines (fx.c): mu-law, 8 bits a sample. MULAW_ENC: |x| >> 4 (0 .. 2047) -> the 7-bit
    # magnitude code; MULAW_DEC: the code -> |x| (Q15)
    mu = 255.0
    enc = [min(127, int(round(127 * math.log1p(mu * (i * 16 + 8) / 32768) / math.log1p(mu)))) for i in range(2048)]
    dec = [int(round(32767 * ((1 + mu) ** (c / 127) - 1) / mu)) for c in range(128)]
    L += arr("MULAW_ENC", "uint8_t", enc, 24, ram=True)
    L += arr("MULAW_DEC", "int16_t", dec, 16, ram=True)
    L += wave_tables()
    L += single_tables()
    L += curve_tables()
    Path(path).write_text("\n".join(L) + "\n")
    print(f"tables: {path}")


# ---------------------------------------------------------------- the waves (osc.c) ---
# Each wave: WT_LV levels, level k keeping 128 >> k harmonics in WT_LEN[k] points (+ 1: the first again).
WT_LV = 8
WT_LEN = [256, 128, 64, 64, 64, 64, 64, 64]


def prim(k, n):
    """PRIM: sine, triangle, saw, square"""
    if k == 0:
        return 1.0 if n == 1 else 0.0
    if k == 1:
        return (8 / math.pi ** 2 / n ** 2 * (-1 if (n // 2) % 2 else 1)) if n % 2 else 0.0
    if k == 2:
        return 2 / math.pi / n * (-1 if n % 2 == 0 else 1)
    return 4 / math.pi / n if n % 2 else 0.0


def harm(k, n):
    """HARM: sixteen waves sweeping through combinations of harmonics, from a sine with its octave towards
    bright, then hollow and formant-like spectra (this firmware's own set)"""
    t = [
        {1: 1, 2: 0.5},
        {1: 1, 3: 0.45},
        {1: 1, 2: 0.6, 3: 0.4},
        {1: 1, 2: 0.5, 4: 0.35, 8: 0.25},
        {1: 1, 3: 0.5, 5: 0.35, 7: 0.25},
        {i: 1 / i for i in range(1, 9)},
        {i: 1 / i for i in range(1, 17)},
        {i: 1 / i ** 0.7 for i in range(1, 33)},
        {i: 1 / i for i in range(1, 33) if i % 2},
        {i: 1 / i for i in range(1, 33) if i % 3},
        {1: 0.6, 4: 1, 5: 0.8, 6: 0.4},
        {1: 0.5, 7: 1, 8: 0.9, 9: 0.5, 10: 0.2},
        {1: 0.5, 2: 0.2, 11: 1, 12: 0.7, 13: 0.4},
        {i: (1.0 if i in (1, 5, 9, 13, 17, 21) else 0.0) for i in range(1, 24)},
        {i: 1 / i ** 0.4 for i in range(1, 65)},
        {i: math.sin(i * 1.7) / i ** 0.5 for i in range(1, 65)},
    ][k]
    return t.get(n, 0.0)


def fmh_set(k):
    """FM TONE's HARM steps (the Digitone II's, as its DSP holds them: sine-phase partials at 1/h): 0 the sine;
    1..7 saw build-ups; 8..13 h1 and the upper of h3..h8; 14..19 odd sets; 20..23 sets of 1, 5, 7, 9, 11; 24..26
    h1 and every third from h4"""
    S = {0: [1]}
    for t in range(1, 8):
        S[t] = list(range(1, t + 2))
    for t in range(8, 14):
        S[t] = [1] + list(range(t - 5, 9))
    S.update({14: [1, 3, 8], 15: [1, 3], 16: [1, 3, 5], 17: [1, 3, 5, 7], 18: [1, 3, 5, 7, 9], 19: [1, 3, 5, 7, 9, 11],
              20: [1, 5, 7, 9, 11], 21: [1, 5], 22: [1, 5, 9], 23: [1, 5, 9, 11], 24: [1, 4], 25: [1, 4, 7],
              26: [1, 4, 7, 10]})
    return S[k]


def drum_set(k):
    """FM DRUM's operator waves (the Digitone II's 33, by their partials, at 1/h): 0 the sine; 1..7 saw
    build-ups to 8; 8..13 h1 and the upper of h3..h8; 14 h1, 3, 8; 15..22 odd build-ups to 17; 23..26 sets of 1,
    5, 7, 9, 11; 27..32 h1 and every third from 4"""
    if k == 0:
        return [1]
    if k <= 7:
        return list(range(1, k + 2))
    if k <= 13:
        return [1] + list(range(k - 5, 9))
    if k == 14:
        return [1, 3, 8]
    if k <= 22:
        return list(range(1, 2 * (k - 15) + 4, 2))
    if k <= 26:
        return [[1, 5, 7, 9, 11], [1, 5], [1, 5, 9], [1, 5, 9, 11]][k - 23]
    return [1] + list(range(4, 3 * (k - 27) + 5, 3))


SC_LEN = 256


def single(parts):
    d = [sum(math.sin(2 * math.pi * h * i / SC_LEN) / h for h in parts) for i in range(SC_LEN)]
    peak = max(abs(x) for x in d) or 1.0
    v = [int(round(32767 * x / peak)) for x in d]
    return v + [v[0]]


def single_tables():
    data = []
    for k in range(27):
        data += single(fmh_set(k))
    for k in range(33):
        data += single(drum_set(k))
    L = ["/* single cycles (no band-limited levels): FM TONE's 27 HARM waves, then FM DRUM's 33 operator waves,",
         f" * {SC_LEN} + 1 points each */", f"#define SC_LEN {SC_LEN}u", "#define SC_FMH0 0u", "#define SC_FMH_N 27u",
         "#define SC_DRUM0 27u", "#define SC_DRUM_N 33u", f"#define SC_TOTAL {len(data)}u"]
    return L + arr("SC_DATA", "int16_t", data, 16)


def wave(fn, k):
    out = []
    for lv in range(WT_LV):
        N, H = WT_LEN[lv], 128 >> lv
        d = [0.0] * N
        for n in range(1, H + 1):
            a = fn(k, n)
            if a:
                for i in range(N):
                    d[i] += a * math.sin(2 * math.pi * n * i / N)
        out.append(d)
    peak = max(max(abs(x) for x in d) for d in out) or 1.0
    vals = []
    for d in out:
        vals += [int(round(32767 * x / peak)) for x in d] + [int(round(32767 * d[0] / peak))]
    return vals


def wave_tables():
    lists = [("PRIM", prim, 4), ("HARM", harm, 16)]
    data, L, w = [], [], 0
    for name, fn, n in lists:
        L += [f"#define WV_{name}0 {w}u", f"#define WV_{name}_N {n}u"]
        for k in range(n):
            data += wave(fn, k)
        w += n
    per = sum(WT_LEN) + WT_LV
    offs, sh, o = [], [], 0
    for N in WT_LEN:
        offs.append(o)
        sh.append(32 - int(math.log2(N)))
        o += N + 1
    L = [f"#define WT_LV {WT_LV}u", f"#define WT_WAVE {per}u", f"#define WT_TOTAL {len(data)}u"] + L
    L += arr("WT_OFF", "uint16_t", offs, 8) + arr("WT_SH", "uint8_t", sh, 8)
    L += ["/* the waves (osc.c), WT_WAVE points each, level after level */"]
    L += arr("WT_DATA", "int16_t", data, 16)
    return L

# ------------------------------------------------------------- the Digitone II's curves (docs/dt2-curves.md) ---
# Formulas fitted to the curves its DSP uses (read from the owner's copy of the firmware; docs/dt2-curves.md): the
# tables below are generated from these fits, not copied. Times in microseconds (INF = 0xFFFFFFFF), levels Q15.
INF = 0xFFFFFFFF


def loglog(c, v):
    x = math.log(v / 127)
    return math.exp(sum(ci * x ** i for i, ci in enumerate(c)))


def logpoly(c, v):
    x = v / 127
    return math.exp(sum(ci * x ** i for i, ci in enumerate(c)))


AATK_LL = [7.227839, 2.342741, -0.112062, -0.034217]       # AMP attack (and the FLTR envelope's), ms, v 1 .. 110
AATK_TOP = [1250, 1500, 1750, 2000, 2500, 3000, 4000, 5000, 6000, 9000, 12000, 15000, 18000, 21000, 24000, 27000, 30000]
AHOLD_LL = [9.201551, 2.429755, -0.047256, -0.021332]      # AMP HOLD, ms
ADEC_LL = [10.298888, 2.426723, -0.049505, -0.021872]      # AMP DEC and REL, ms to -60 dB
FDEC_LL = [10.263682, 5.17158, 1.944747, 0.419187, 0.033418]   # FLTR DEC and REL, ms to -60 dB
OPATK_LL = [9.899144, 2.445818, -0.039988, -0.022153]      # FM TONE operator attack, ms
OPDEC_LL = [10.997899, 2.452892, -0.02557, -0.016248]      # .. decay, ms to -60 dB
LEVV_LP = [-7.45646, -0.55136, 3.69881, 8.75002, -16.55205, 7.27872]   # FM TONE LEV curve / v (0 .. 1 at 127)
BITS_LP = [2.77673, -2.60659, 0.81133, -5.21024, 8.4302, -3.55777]     # BIT REDUCTION, bits (v >= 1)
RVSH_LP = [-2.80771, 5.41741, -8.30061, 10.84599, -8.30429, 2.5842]    # the reverb's shelf coefficient (FREQ)
DTA_TOP = [0.075, 0.1, 0.125, 0.15, 0.25, 0.3, 0.4, 0.5]    # DTUN 120 .. 127, operator A's ratio added
DTB_TOP = [0.2, 0.25, 0.3, 0.4, 0.5, 0.6, 0.7, 0.75]        # .. operator B2's
SW_ROWS = [0, 16, 32, 64, 96, 127]                          # SWARMER DET: six voices' offsets, cents, at these values
SW_CENTS = [[-0.57, -0.33, -0.10, 0.10, 0.32, 0.56], [-4.41, -2.52, -0.78, 0.80, 2.49, 4.30],
            [-9.03, -5.16, -1.60, 1.63, 5.08, 8.77], [-18.96, -10.81, -3.35, 3.41, 10.62, 18.32],
            [-47.79, -27.15, -8.38, 8.51, 26.43, 45.43], [-201.78, -112.44, -34.13, 34.13, 104.41, 176.69]]


def curve_tables():
    us = lambda ms: min(INF - 1, int(round(ms * 1000)))
    aatk = [21] + [us(loglog(AATK_LL, v)) for v in range(1, 111)] + [t * 1000 for t in AATK_TOP]
    ahold = [42] + [us(loglog(AHOLD_LL, v)) for v in range(1, 127)] + [INF]
    adec = [146] + [us(loglog(ADEC_LL, v)) for v in range(1, 127)] + [INF]
    fdel = [us(max(0.6667 * v, 3000 * (v / 127) ** 3)) for v in range(128)]
    fdec = [0] + [us(loglog(FDEC_LL, v)) for v in range(1, 127)] + [INF]
    opatk = [0] + [us(loglog(OPATK_LL, v)) for v in range(1, 128)]
    opdec = [0] + [us(loglog(OPDEC_LL, v)) for v in range(1, 128)]
    lev = [0] + [min(32767, int(round(32767 * v * logpoly(LEVV_LP, v)))) for v in range(1, 127)] + [32767]
    bits = [31 * 256] + [int(round(256 * logpoly(BITS_LP, v))) for v in range(1, 128)]
    rvsh = [int(round(32767 * logpoly(RVSH_LP, v))) for v in range(128)]
    dta = [0] + [int(round(65536 * 0.00015045 * 1.05 ** v)) for v in range(1, 120)] + [int(round(65536 * x)) for x in DTA_TOP]
    dtb = [0] + [int(round(65536 * 0.00008348 * 1.065 ** v)) for v in range(1, 120)] + [int(round(65536 * x)) for x in DTB_TOP]
    det = []                                                # (log-interpolated between the rows; Q16 semitones)
    for v in range(128):
        j = max(i for i in range(len(SW_ROWS)) if SW_ROWS[i] <= v) if v < 127 else len(SW_ROWS) - 2
        j = min(j, len(SW_ROWS) - 2)
        f = (v - SW_ROWS[j]) / (SW_ROWS[j + 1] - SW_ROWS[j])
        for k in range(6):
            a, b = abs(SW_CENTS[j][k]), abs(SW_CENTS[j + 1][k])
            c = math.copysign(math.exp(math.log(a) + f * (math.log(b) - math.log(a))), SW_CENTS[j][k])
            det.append(int(round(c / 100 * 65536)))
    L = ["/* the Digitone II's curves, fitted (tools/gen_tables.py, docs/dt2-curves.md): times in us, 0xFFFFFFFF none */"]
    L += arr("T_AATK", "uint32_t", aatk, 8) + arr("T_AHOLD", "uint32_t", ahold, 8) + arr("T_ADEC", "uint32_t", adec, 8)
    L += arr("T_FDEL", "uint32_t", fdel, 8) + arr("T_FDEC", "uint32_t", fdec, 8)
    L += arr("T_OPATK", "uint32_t", opatk, 8) + arr("T_OPDEC", "uint32_t", opdec, 8)
    L += ["/* FM TONE: the LEV curve (Q15 of 2.205 cycles); DTUN's ratio added to A and B2 (Q16) */"]
    L += arr("T_LEV", "uint16_t", lev, 12) + arr("T_DTA", "uint32_t", dta, 8) + arr("T_DTB", "uint32_t", dtb, 8)
    L += ["/* BIT REDUCTION: bits x 256 (31: off); the reverb's shelf coefficient (Q15) */"]
    L += arr("T_BITS", "uint16_t", bits, 12) + arr("T_RVSH", "uint16_t", rvsh, 12)
    L += ["/* SWARMER DET: each of the six voices' offset, semitones Q16, [v][6] */"]
    L += arr("T_SWDET", "int32_t", det, 12)
    return L


if __name__ == "__main__":
    main(sys.argv[1])
