# BIGORNA: the splash screen's logo, rendered to a C header -- the anvil and the lettering of docs/assets/logo-dark.svg
# (tools/make_logo.py's shapes: the anvil outlined with mitred corners, BIGORNA in Michroma, the same letter spacing),
# laid one over the other for the square screen. Two 4-bit alpha bitmaps, two pixels a byte (high nibble first), rows
# top to bottom; drawn 8 times larger and averaged down, so the edges are anti-aliased.
"""tools/gen_logo.py OUT.h"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_logo import A_BOT, A_TOP, ANVIL, CAP, FONT, STROKE, TRACK  # noqa: E402

SS = 8                   # the supersampling
ANVIL_W = 176            # the anvil's width on the screen, px (its outline included)
WORD_W = 224             # the lettering's


def anvil_points():
    pts = []
    for tok in ANVIL.replace("M", "").replace("Z", "").split("L"):
        x, y = tok.split(",")
        pts.append((float(x), float(y)))
    return pts


def offset(pts, d):
    """the polygon's outline moved d along the edges' normals (> 0: outwards, the path being clockwise on screen),
    the corners mitred: each new corner where the two moved edges meet"""
    n, out = len(pts), []
    lines = []
    for i in range(n):
        (x0, y0), (x1, y1) = pts[i], pts[(i + 1) % n]
        ex, ey = x1 - x0, y1 - y0
        ln = (ex * ex + ey * ey) ** 0.5
        nx, ny = -ey / ln, ex / ln            # (left of the edge, y down: outside for a clockwise path)
        lines.append(((x0 + nx * d, y0 + ny * d), (ex, ey)))
    for i in range(n):
        (p, e), (q, f) = lines[i - 1], lines[i]
        den = e[0] * f[1] - e[1] * f[0]
        t = ((q[0] - p[0]) * f[1] - (q[1] - p[1]) * f[0]) / den
        out.append((p[0] + e[0] * t, p[1] + e[1] * t))
    return out


def area(pts):
    return sum(pts[i][0] * pts[i - 1][1] - pts[i - 1][0] * pts[i][1] for i in range(len(pts))) / 2


def render_anvil():
    pts = anvil_points()
    s_unit = CAP / (A_BOT - A_TOP)                 # (make_logo's: the anvil's face to its feet as the capitals)
    half = STROKE / 2 / s_unit                     # the outline's half, in the path's units
    outer, inner = offset(pts, half), offset(pts, -half)
    if abs(area(outer)) < abs(area(inner)):        # (outwards, whichever way the path turns)
        outer, inner = inner, outer
    x0 = min(p[0] for p in outer)
    y0 = min(p[1] for p in outer)
    wu = max(p[0] for p in outer) - x0
    hu = max(p[1] for p in outer) - y0
    k = ANVIL_W / wu                               # px a unit
    w, h = ANVIL_W, int(hu * k + 0.999) + 1
    img = Image.new("L", (w * SS, h * SS), 0)
    d = ImageDraw.Draw(img)
    tr = lambda poly: [((x - x0) * k * SS, (y - y0) * k * SS) for x, y in poly]   # noqa: E731
    d.polygon(tr(outer), fill=255)
    d.polygon(tr(inner), fill=0)
    return img.reduce(SS)


def render_word(text="BIGORNA"):
    from fontTools.ttLib import TTFont
    f = TTFont(FONT)
    cmap, hmtx, upem = f.getBestCmap(), f["hmtx"], f["head"].unitsPerEm
    cap = f["OS/2"].sCapHeight
    adv = [hmtx[cmap[ord(c)]][0] for c in text]
    # the width in font units, the last letter to its ink's right edge
    glyf = f["glyf"][cmap[ord(text[-1])]]
    width = sum(adv[:-1]) + TRACK * upem * (len(text) - 1) + glyf.xMax
    k = WORD_W / width                             # px a font unit
    h = int(cap * k + 0.999) + 2
    img = Image.new("L", (WORD_W * SS + SS, h * SS), 0)
    font = ImageFont.truetype(str(FONT), int(round(upem * k * SS)))
    d = ImageDraw.Draw(img)
    x = 0.0
    for c, a in zip(text, adv):
        d.text((x * k * SS, cap * k * SS + SS), c, font=font, fill=255, anchor="ls")
        x += a + TRACK * upem
    img = img.reduce(SS)
    return img.crop((0, 0, WORD_W, h)), round(cap * k)


def emit(name, img, L):
    w, h = img.size
    px = img.tobytes()
    data = []
    for y in range(h):
        row = [min(15, (px[y * w + x] + 8) // 17) for x in range(w)] + [0]
        for x in range(0, w, 2):
            data.append((row[x] << 4) | row[x + 1])
    L.append(f"#define {name}_W {w}")
    L.append(f"#define {name}_H {h}")
    L.append(f"static const uint8_t {name}[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        L.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    L.append("};")
    return len(data)


def main(path):
    L = [f"/* generated by tools/gen_logo.py from tools/make_logo.py's shapes and {FONT.name} */", "#pragma once",
         "#include <stdint.h>", ""]
    a = emit("LOGO_ANVIL", render_anvil(), L)
    word, cap = render_word()
    b = emit("LOGO_WORD", word, L)
    Path(path).write_text("\n".join(L) + "\n")
    print(f"logo: anvil {a} B, lettering {b} B (capitals {cap} px)")


if __name__ == "__main__":
    main(sys.argv[1])
